// OscarLexerBase state
type OscarLexerBase struct {
	*antlr.BaseLexer

	lastToken   antlr.Token
	reservedMap map[string]bool
}

// NextToken from the character stream.
func (l *OscarLexerBase) NextToken() antlr.Token {
	next := l.BaseLexer.NextToken() // Get next token
	if next.GetChannel() == antlr.TokenDefaultChannel {
		// Keep track of the last token on default channel
		l.lastToken = next
	}
	return next
}

// IsRegexPossible returns true if the lexer can match a
// regex literal.
func (l *OscarLexerBase) IsNewlineAtPos(pos int) bool {
	if l.lastToken == nil {
		return true
	}
	la := l.GetInputStream().LA(pos)
	return la == -1 || la == '\n'
}

